# while loops
i = 1
while (i < 6):
    print(i)
    i = i + 1

print("Out of while loop!")

# Print even numbers from 1 - 10 using while loop
counter = 1
while(counter <= 10):
    if(counter % 2 == 0):
        print(counter)
    counter = counter + 1

print("End of while loop")

