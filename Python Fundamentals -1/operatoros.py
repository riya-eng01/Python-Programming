# Operators in python

# Arithmetic operators
a = 34
b = 2
print("a + b = ", a + b)
print("a - b = ", a - b)
print("a * b = ", a * b)
print("a / b = ", a / b)
print("a % b = ", a % b)
print("a // b = ", a // b) # floor division - Remove decimals
print("a ** b = ", a**b)

# Conditional operators
print(a > 4)
print(a < 4)
print(a <= 4)
print(a >= 4)
print(a == 4) # Is a equal to 4?
print(a == 34)
print(a != 34) # Not equal to

# Logical Operators
print("For and operator...")
print(True and True)
print(True and False)
print(False and True)
print(False and False)

print("For or operator....")
print(True or True)
print(True or False)
print(False or True)
print(False or False)

print("For not operator")
print(not True)
print(not False)

# Assignment operators
x = 32
print(x)
x += 3
print(x)
x -= 5
print(x)
x *= 3
print(x)
x /= 3
print(x)
x **= 2 # exponentiation assignment operator
print(x)